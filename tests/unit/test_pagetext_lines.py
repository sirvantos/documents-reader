"""Chars → segments → lines (research R-2) on hand-made char records, plus one real PDF."""

from __future__ import annotations

from pathlib import Path

import pypdfium2 as pdfium

from docreader.pagetext import Char, Line, build_lines, read_page_chars
from tests.synthetic.make_pdfs import CONTRACT_RU_PAGES, make_contract_ru

H = 10.0  # char height
W = 5.0  # char width


def word(text: str, left: float, bottom: float = 100.0, *, h: float = H) -> list[Char]:
    """Chars of `text` side by side, each W wide, starting at `left`."""
    return [
        Char(c, (left + i * W, bottom, left + (i + 1) * W, bottom + h))
        for i, c in enumerate(text)
    ]


def gen(text: str, left: float, bottom: float = 100.0) -> Char:
    """A char generated by PDFium (space, line break)."""
    return Char(text, (left, bottom, left + 0.0, bottom + H), generated=True)


def test_empty_input_gives_no_lines() -> None:
    assert build_lines([]) == []


def test_single_word_is_one_line() -> None:
    lines = build_lines(word("abc", 10))
    assert len(lines) == 1
    assert lines[0].index == 0
    assert lines[0].text == "abc"
    assert lines[0].bbox == (10.0, 100.0, 25.0, 110.0)


def test_small_gap_stays_in_one_segment() -> None:
    # gap 15 == 1.5 * 10: not exceeded, so no break and no space is invented
    chars = word("ab", 0) + word("cd", 10 + 15)
    assert build_lines(chars)[0].text == "abcd"


def test_large_gap_splits_segments_joined_with_one_space() -> None:
    chars = word("ab", 0) + word("cd", 10 + 15.5)
    lines = build_lines(chars)
    assert len(lines) == 1
    assert lines[0].text == "ab cd"
    assert [s.text for s in lines[0].segments] == ["ab", "cd"]


def test_gap_threshold_uses_larger_height_of_the_two_chars() -> None:
    small = word("a", 0, h=4.0)  # right edge 5
    big = word("b", 5 + 7.0, h=10.0)  # gap 7 > 1.5*4 but <= 1.5*10
    assert build_lines(small + big)[0].text == "ab"


def test_generated_line_break_splits_segments_on_same_baseline() -> None:
    chars = word("ab", 0) + [gen("\n", 10)] + word("cd", 10)
    lines = build_lines(chars)
    assert len(lines) == 1
    assert lines[0].text == "ab cd"
    assert len(lines[0].segments) == 2


def test_generated_cr_also_breaks() -> None:
    chars = word("ab", 0) + [gen("\r", 10), gen("\n", 10)] + word("cd", 10)
    assert build_lines(chars)[0].text == "ab cd"


def test_generated_space_inside_segment_is_kept_as_one_space() -> None:
    chars = word("ab", 0) + [gen(" ", 10)] + word("cd", 10)
    assert build_lines(chars)[0].text == "ab cd"


def test_runs_of_spaces_collapse_to_one() -> None:
    chars = word("ab", 0) + [gen(" ", 10), gen(" ", 10)] + word("cd", 10)
    assert build_lines(chars)[0].text == "ab cd"


def test_leading_and_trailing_spaces_of_segment_are_stripped() -> None:
    chars = [gen(" ", 0)] + word("ab", 0) + [gen(" ", 10)]
    lines = build_lines(chars)
    assert lines[0].text == "ab"
    assert lines[0].segments[0].text == "ab"


def test_whitespace_only_input_gives_no_lines() -> None:
    assert build_lines([gen(" ", 0), gen("\n", 0)]) == []


def test_whitespace_chars_do_not_count_toward_boxes() -> None:
    wide_space = Char(" ", (10.0, 0.0, 200.0, 500.0))
    chars = word("ab", 0) + [wide_space] + word("cd", 10)
    line = build_lines(chars)[0]
    assert line.text == "ab cd"
    assert line.bbox == (0.0, 100.0, 20.0, 110.0)


def test_lines_with_vertical_overlap_of_half_height_are_merged() -> None:
    upper = word("ab", 0, bottom=100.0)  # 100..110
    other = word("cd", 50, bottom=105.0)  # 105..115, overlap 5 == half of 10
    lines = build_lines(upper + other)
    assert len(lines) == 1
    assert lines[0].text == "ab cd"


def test_less_than_half_overlap_makes_separate_lines() -> None:
    upper = word("ab", 0, bottom=100.0)
    other = word("cd", 50, bottom=106.0)  # overlap 4 < 5
    lines = build_lines(upper + other)
    assert [ln.text for ln in lines] == ["cd", "ab"]


def test_overlap_is_measured_against_the_smaller_height() -> None:
    big = word("ab", 0, bottom=100.0, h=20.0)  # 100..120
    small = word("cd", 50, bottom=118.0, h=4.0)  # 118..122, overlap 2 == half of 4
    assert len(build_lines(big + small)) == 1


def test_lines_are_ordered_top_to_bottom_whatever_the_char_order() -> None:
    chars = word("low", 0, bottom=50) + word("high", 0, bottom=200) + word("mid", 0, bottom=100)
    lines = build_lines(chars)
    assert [ln.text for ln in lines] == ["high", "mid", "low"]
    assert [ln.index for ln in lines] == [0, 1, 2]


def test_segments_are_ordered_left_to_right() -> None:
    chars = word("right", 200) + word("left", 0)
    lines = build_lines(chars)
    assert len(lines) == 1
    assert lines[0].text == "left right"
    assert lines[0].bbox[0] == 0.0
    assert lines[0].bbox[2] == 200 + 5 * W


def test_line_bbox_is_union_of_chars() -> None:
    chars = word("ab", 10, bottom=100.0) + word("cd", 100, bottom=103.0, h=12.0)
    assert build_lines(chars)[0].bbox == (10.0, 100.0, 110.0, 115.0)


def test_unicode_hyphen_marker_is_kept_in_text() -> None:
    chars = word("ab", 0) + [Char("￾", (10.0, 100.0, 15.0, 110.0))]
    assert build_lines(chars)[0].text == "ab￾"


def test_line_to_json_shape() -> None:
    line = build_lines(word("ab", 10.123, bottom=100.0))[0]
    data = line.to_json()
    assert list(data) == ["i", "text", "bbox", "role", "column", "table"]
    assert data["i"] == 0
    assert data["text"] == "ab"
    assert data["bbox"] == [10.12, 100.0, 20.12, 110.0]
    assert data["role"] == "body"
    assert data["column"] is None
    assert data["table"] is None


def test_line_type_is_exported() -> None:
    assert isinstance(build_lines(word("a", 0))[0], Line)


# --- real PDF ---------------------------------------------------------------


def test_contract_ru_pdf_lines_match_source_text(tmp_path: Path) -> None:
    path = make_contract_ru(tmp_path / "contract.pdf")
    pdf = pdfium.PdfDocument(str(path))
    try:
        assert len(pdf) == len(CONTRACT_RU_PAGES)
        for number, expected in enumerate(CONTRACT_RU_PAGES):
            page = pdf[number]
            try:
                width, height = page.get_size()
                lines = build_lines(read_page_chars(page))
            finally:
                page.close()
            assert [ln.text for ln in lines] == list(expected)
            assert [ln.index for ln in lines] == list(range(len(expected)))
            for ln in lines:
                left, bottom, right, top = ln.bbox
                assert 0 <= left < right <= width
                assert 0 <= bottom < top <= height
    finally:
        pdf.close()
