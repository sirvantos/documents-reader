def make_digital(path: str | Path, pages: int = 3, text_seed: str = "A") -> Path:
    """Digital PDF: text on every page, no pictures. text_seed tells files apart."""
    return _write(path, _digital_bytes(pages, text_seed))


def make_image_only(path: str | Path, pages: int = 2) -> Path:
    """Every page is a full-page picture, no text."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            _full_page_image(c, seed=100 + n)
            c.showPage()

    return _write(path, _pdf(draw))


def make_mixed(path: str | Path, pages: int = 4) -> Path:
    """Pages 1..N-1 have text, the last page is a full-page picture without text."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(1, pages):
            _text_block(c, "Synthetic mixed document", n)
            c.showPage()
        if pages >= 1:
            _full_page_image(c, seed=150 + pages)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_with_invisible_text(path: str | Path, pages: int = 2) -> Path:
    """Full-page picture with text on top of it in render mode 3 (invisible)."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            _full_page_image(c, seed=200 + n)
            text = c.beginText(72, PAGE_H - 72)
            text.setTextRenderMode(3)
            text.setFont("Helvetica", 9)
            for i in range(12):
                text.textLine(
                    f"Hidden text layer {n + 1}.{i + 1}: {_LINES[i % len(_LINES)]}"
                )
            c.drawText(text)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_strips(path: str | Path, pages: int = 1) -> Path:
    """The whole page is covered by five horizontal picture strips, no text."""
    strips = 5
    # bounds match exactly: top of strip i = bottom of strip i+1, last = PAGE_H
    bounds = [PAGE_H * i / strips for i in range(strips)] + [PAGE_H]

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            for i in range(strips):
                y0, y1 = bounds[i], bounds[i + 1]
                strip = _noise_image(
                    300 + n * strips + i, _RASTER_W, _RASTER_H // strips
                )
                c.drawImage(ImageReader(strip), 0, y0, width=PAGE_W, height=y1 - y0)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_in_form(path: str | Path, pages: int = 1) -> Path:
    """Full-page picture inside a form XObject.

    Inside the form the picture takes half of the page; the scale of 2 before doForm
    stretches it to the whole page. Form and page coordinates differ; no text.
    """

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            name = f"form{n}"
            c.beginForm(name)
            c.drawImage(
                ImageReader(_noise_image(400 + n)),
                0,
                0,
                width=PAGE_W / 2,
                height=PAGE_H / 2,
            )
            c.endForm()
            c.saveState()
            c.scale(2, 2)
            c.doForm(name)
            c.restoreState()
            c.showPage()

    return _write(path, _pdf(draw))


