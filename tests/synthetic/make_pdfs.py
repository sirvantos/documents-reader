def _register_cyrillic_font() -> None:
    """Registers DejaVu Sans once; repeated calls do nothing."""
    if _CYRILLIC_FONT not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(_CYRILLIC_FONT, str(_CYRILLIC_FONT_PATH)))


def _ru_page(
    c: canvas.Canvas,
    lines: tuple[str, ...],
    *,
    x: float = 72,
    y_top: float = PAGE_H - 72,
    size: float = 11,
    leading: float = 16,
) -> None:
    """Draws one line per drawString call at known positions; no wrapping."""
    _register_cyrillic_font()
    c.setFont(_CYRILLIC_FONT, size)
    for i, line in enumerate(lines):
        c.drawString(x, y_top - i * leading, line)


