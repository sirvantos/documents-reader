"""Synthetic files for auto-tests (research R-10 and R-5).

Each function `make_<kind>(path, ...)` writes a file to `path` and returns it.
The content is generated by code: text is Latin-only, pictures are noise with a fixed
seed. A call with the same arguments gives the same bytes (duplicates for tests); different
kinds and arguments give different bytes. Real contracts never go here (principle I).

Run the set for manual checking:
    uv run python -m tests.synthetic.make_pdfs <folder>
"""

from __future__ import annotations

import argparse
import io
import random
import sys
import zipfile
from collections.abc import Callable
from pathlib import Path

from PIL import Image, ImageDraw
from reportlab.lib.pagesizes import A4
from reportlab.lib.pdfencrypt import StandardEncryption
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

PAGE_W, PAGE_H = A4
_RASTER_W, _RASTER_H = 300, 425  # full-page raster picture

_LINES = (
    "Lorem ipsum dolor sit amet, consectetur adipiscing elit.",
    "Sed do eiusmod tempor incididunt ut labore et dolore magna aliqua.",
    "Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris.",
    "Duis aute irure dolor in reprehenderit in voluptate velit esse.",
    "Excepteur sint occaecat cupidatat non proident, sunt in culpa.",
    "Nemo enim ipsam voluptatem quia voluptas sit aspernatur aut odit.",
)

_DOCX_CONTENT_TYPES = (
    b'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    b'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
    b'<Default Extension="xml" ContentType="application/xml"/>'
    b'<Override PartName="/word/document.xml" '
    b'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
    b"</Types>"
)
_DOCX_DOCUMENT = (
    b'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    b'<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
    b"<w:body><w:p><w:r><w:t>Synthetic lorem ipsum document for tests.</w:t></w:r></w:p>"
    b"</w:body></w:document>"
)


# --- helper functions --------------------------------------------------------


def _noise_image(
    seed: int, width: int = _RASTER_W, height: int = _RASTER_H
) -> Image.Image:
    """Grey noise image; the same seed gives the same picture."""
    rng = random.Random(seed)
    return Image.frombytes("L", (width, height), rng.randbytes(width * height))


def _sample_picture(width: int, height: int) -> Image.Image:
    """Small colour picture with shapes (for JPEG, PNG and the logo)."""
    img = Image.new("RGB", (width, height), (240, 240, 240))
    draw = ImageDraw.Draw(img)
    draw.rectangle([10, 10, width // 2, height // 2], fill=(30, 90, 160))
    draw.ellipse([width // 2, height // 3, width - 10, height - 10], fill=(200, 80, 40))
    return img


def _pdf(draw_pages: Callable[[canvas.Canvas], None], encrypt=None) -> bytes:
    """Builds a PDF in memory; draw_pages calls showPage() itself after each page."""
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4, invariant=1, encrypt=encrypt)
    draw_pages(c)
    c.save()
    return buf.getvalue()


def _write(path: str | Path, data: bytes) -> Path:
    target = Path(path)
    target.write_bytes(data)
    return target


def _text_block(
    c: canvas.Canvas, title: str, page_no: int, top: float = PAGE_H - 110
) -> None:
    c.setFont("Helvetica-Bold", 14)
    c.drawString(72, PAGE_H - 72, title)
    c.setFont("Helvetica", 11)
    y = top
    for line in _LINES[:4]:
        c.drawString(72, y, f"{page_no}. {line}")
        y -= 18


def _full_page_image(c: canvas.Canvas, seed: int) -> None:
    c.drawImage(ImageReader(_noise_image(seed)), 0, 0, width=PAGE_W, height=PAGE_H)


def _digital_bytes(pages: int, text_seed: str) -> bytes:
    def draw(c: canvas.Canvas) -> None:
        for n in range(1, pages + 1):
            _text_block(c, f"Synthetic document {text_seed}", n)
            c.showPage()

    return _pdf(draw)


# --- PDF ---------------------------------------------------------------------


def make_digital(path: str | Path, pages: int = 3, text_seed: str = "A") -> Path:
    """Digital PDF: text on every page, no pictures. text_seed tells files apart."""
    return _write(path, _digital_bytes(pages, text_seed))


def make_image_only(path: str | Path, pages: int = 2) -> Path:
    """Every page is a full-page picture, no text."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            _full_page_image(c, seed=100 + n)
            c.showPage()

    return _write(path, _pdf(draw))


def make_mixed(path: str | Path, pages: int = 4) -> Path:
    """Pages 1..N-1 have text, the last page is a full-page picture without text."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(1, pages):
            _text_block(c, "Synthetic mixed document", n)
            c.showPage()
        if pages >= 1:
            _full_page_image(c, seed=150 + pages)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_with_invisible_text(path: str | Path, pages: int = 2) -> Path:
    """Full-page picture with text on top of it in render mode 3 (invisible)."""

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            _full_page_image(c, seed=200 + n)
            text = c.beginText(72, PAGE_H - 72)
            text.setTextRenderMode(3)
            text.setFont("Helvetica", 9)
            for i in range(12):
                text.textLine(
                    f"Hidden text layer {n + 1}.{i + 1}: {_LINES[i % len(_LINES)]}"
                )
            c.drawText(text)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_strips(path: str | Path, pages: int = 1) -> Path:
    """The whole page is covered by five horizontal picture strips, no text."""
    strips = 5
    # bounds match exactly: top of strip i = bottom of strip i+1, last = PAGE_H
    bounds = [PAGE_H * i / strips for i in range(strips)] + [PAGE_H]

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            for i in range(strips):
                y0, y1 = bounds[i], bounds[i + 1]
                strip = _noise_image(
                    300 + n * strips + i, _RASTER_W, _RASTER_H // strips
                )
                c.drawImage(ImageReader(strip), 0, y0, width=PAGE_W, height=y1 - y0)
            c.showPage()

    return _write(path, _pdf(draw))


def make_image_in_form(path: str | Path, pages: int = 1) -> Path:
    """Full-page picture inside a form XObject.

    Inside the form the picture takes half of the page; the scale of 2 before doForm
    stretches it to the whole page. Form and page coordinates differ; no text.
    """

    def draw(c: canvas.Canvas) -> None:
        for n in range(pages):
            name = f"form{n}"
            c.beginForm(name)
            c.drawImage(
                ImageReader(_noise_image(400 + n)),
                0,
                0,
                width=PAGE_W / 2,
                height=PAGE_H / 2,
            )
            c.endForm()
            c.saveState()
            c.scale(2, 2)
            c.doForm(name)
            c.restoreState()
            c.showPage()

    return _write(path, _pdf(draw))


def make_logo_and_text(path: str | Path, pages: int = 1) -> Path:
    """Small logo (about 10% of the page area) in the top-right corner, and text."""
    logo_side = PAGE_W * 0.316  # square ≈ 10% of A4 area at PAGE_W x PAGE_H
    logo = ImageReader(_sample_picture(200, 200))

    def draw(c: canvas.Canvas) -> None:
        for n in range(1, pages + 1):
            c.drawImage(
                logo,
                PAGE_W - 72 - logo_side,
                PAGE_H - 72 - logo_side,
                width=logo_side,
                height=logo_side,
            )
            _text_block(c, "Synthetic document with logo", n, top=PAGE_H - 300)
            c.showPage()

    return _write(path, _pdf(draw))


def make_blank_page(path: str | Path, pages: int = 1) -> Path:
    """Blank pages: no text, no pictures."""

    def draw(c: canvas.Canvas) -> None:
        for _ in range(pages):
            c.showPage()

    return _write(path, _pdf(draw))


def make_encrypted(path: str | Path) -> Path:
    """Text PDF with the user password «secret»: it does not open without the password."""
    encryption = StandardEncryption(
        "secret", ownerPassword="synthetic-owner", canPrint=1
    )

    def draw(c: canvas.Canvas) -> None:
        _text_block(c, "Synthetic encrypted document", 1)
        c.showPage()

    return _write(path, _pdf(draw, encrypt=encryption))


def make_damaged(path: str | Path) -> Path:
    """Digital PDF cut in half; the %PDF- header is kept."""
    data = _digital_bytes(3, "damaged")
    return _write(path, data[: len(data) // 2])


def make_empty(path: str | Path) -> Path:
    """Zero-size file."""
    return _write(path, b"")


def make_no_pages(path: str | Path) -> Path:
    """Minimal PDF with an empty /Pages (/Kids [] /Count 0) and a correct xref table."""
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [] /Count 0 >>",
    ]
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode() + body + b"\nendobj\n"
    xref_offset = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode()
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_offset}\n%%EOF\n"
    ).encode()
    return _write(path, bytes(out))


# --- not PDF: formats recognised by signature (R-5) --------------------------


def make_fake_docx(path: str | Path) -> Path:
    """ZIP archive with [Content_Types].xml and word/document.xml (like a DOCX)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as archive:
        for name, data in (
            ("[Content_Types].xml", _DOCX_CONTENT_TYPES),
            ("word/document.xml", _DOCX_DOCUMENT),
        ):
            # fixed date in the entry, otherwise the bytes depend on the run time
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return _write(path, buf.getvalue())


def make_fake_doc(path: str | Path) -> Path:
    """OLE2 header (DOC format) and zero padding up to 512 bytes."""
    return _write(path, b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + bytes(512 - 8))


def make_jpeg(path: str | Path) -> Path:
    buf = io.BytesIO()
    _sample_picture(240, 180).save(buf, "JPEG", quality=85)
    return _write(path, buf.getvalue())


def make_png(path: str | Path) -> Path:
    buf = io.BytesIO()
    _sample_picture(240, 180).save(buf, "PNG")
    return _write(path, buf.getvalue())


def make_unknown(path: str | Path) -> Path:
    """Plain text without a known signature."""
    return _write(path, b"Plain text note without any known file signature.\n")


# --- demo set ------------------------------------------------------------------


def make_demo_set(directory: str | Path) -> list[Path]:
    """Writes the demo set into the folder and the nested/ subfolder; returns the paths."""
    root = Path(directory)
    nested = root / "nested"
    nested.mkdir(parents=True, exist_ok=True)
    return [
        make_digital(root / "digital.pdf"),
        make_mixed(root / "mixed.pdf"),
        make_image_only(root / "image_only.pdf"),
        make_image_with_invisible_text(root / "image_with_invisible_text.pdf"),
        make_fake_docx(root / "fake.docx"),
        make_jpeg(root / "photo.jpg"),
        make_encrypted(root / "encrypted.pdf"),
        make_damaged(root / "damaged.pdf"),
        make_empty(root / "empty.pdf"),
        make_digital(
            root / "digital_copy.pdf"
        ),  # duplicate of digital.pdf under another name
        make_digital(nested / "digital_other.pdf", text_seed="nested"),
        make_logo_and_text(nested / "logo_and_text.pdf"),
        make_png(nested / "scan.png"),
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Записать синтетический демонстрационный набор."
    )
    parser.add_argument("directory", type=Path, help="папка, куда записать файлы")
    args = parser.parse_args(argv)
    for path in make_demo_set(args.directory):
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
