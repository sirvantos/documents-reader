# --- helper functions --------------------------------------------------------


def _noise_image(
    seed: int, width: int = _RASTER_W, height: int = _RASTER_H
) -> Image.Image:
    """Grey noise image; the same seed gives the same picture."""
    rng = random.Random(seed)
    return Image.frombytes("L", (width, height), rng.randbytes(width * height))


def _sample_picture(width: int, height: int) -> Image.Image:
    """Small colour picture with shapes (for JPEG, PNG and the logo)."""
    img = Image.new("RGB", (width, height), (240, 240, 240))
    draw = ImageDraw.Draw(img)
    draw.rectangle([10, 10, width // 2, height // 2], fill=(30, 90, 160))
    draw.ellipse([width // 2, height // 3, width - 10, height - 10], fill=(200, 80, 40))
    return img


def _pdf(draw_pages: Callable[[canvas.Canvas], None], encrypt=None) -> bytes:
    """Builds a PDF in memory; draw_pages calls showPage() itself after each page."""
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4, invariant=1, encrypt=encrypt)
    draw_pages(c)
    c.save()
    return buf.getvalue()


def _write(path: str | Path, data: bytes) -> Path:
    target = Path(path)
    target.write_bytes(data)
    return target


def _text_block(
    c: canvas.Canvas, title: str, page_no: int, top: float = PAGE_H - 110
) -> None:
    c.setFont("Helvetica-Bold", 14)
    c.drawString(72, PAGE_H - 72, title)
    c.setFont("Helvetica", 11)
    y = top
    for line in _LINES[:4]:
        c.drawString(72, y, f"{page_no}. {line}")
        y -= 18


def _full_page_image(c: canvas.Canvas, seed: int) -> None:
    c.drawImage(ImageReader(_noise_image(seed)), 0, 0, width=PAGE_W, height=PAGE_H)


def _digital_bytes(pages: int, text_seed: str) -> bytes:
    def draw(c: canvas.Canvas) -> None:
        for n in range(1, pages + 1):
            _text_block(c, f"Synthetic document {text_seed}", n)
            c.showPage()

    return _pdf(draw)


